// Запись слова «Гермес» с микрофона гарнитуры.
// Один дубль = WAV-файл 1.2 секунды (слово длится ~0.6-0.8с, остальное — тишина по краям).
// Выход: dataset/raw/real/germes_real_0001.wav, 0002.wav, ...
//        (нативная частота микрофона, 16-bit, моно)
//
// Запуск:  cargo run --bin record -- <папка> <число дублей>
// Пример:  cargo run --bin record -- dataset/raw/real 20

// В Rust, чтобы вызвать метод типа (device.default_input_config(), stream.play(), ...),
// нужно импортировать ТРЕЙТ, в котором этот метод определён. Поэтому use такой:
use cpal::traits::{DeviceTrait, HostTrait, StreamTrait};
// Arc и Mutex — примитивы совместного доступа из нескольких потоков.
// Зачем они здесь — см. комментарий у буфера записи ниже.
use std::sync::{Arc, Mutex};

fn main() {
    // --- Аргументы командной строки ---
    // std::env::args() — итератор по аргументам: [путь к бинарю, arg1, arg2, ...].
    // nth(1) берёт второй элемент и возвращает Option<String>: Some(значение) или None.
    // unwrap_or_else: если None — вычисли запасное значение (замыкание вызывается лениво).
    let out_dir = std::env::args().nth(1).unwrap_or_else(|| "dataset/raw/real".to_string());

    // Второй аргумент — сколько дублей записать за эту сессию.
    // and_then: если есть Some(строка) — передай её в замыкание; если None — так и останется None.
    // parse::<usize>() возвращает Result<usize, ошибка>; .ok() превращает Result в Option:
    // ошибка парсинга («abc» вместо числа) становится None.
    // unwrap_or(10): аргумента нет или это мусор → 10 дублей по умолчанию.
    let count: usize = std::env::args().nth(2).and_then(|s| s.parse().ok()).unwrap_or(10);

    // Создаём выходную папку (вместе со всеми промежуточными, если их нет).
    // expect = unwrap с твоим текстом ошибки: если не вышло — паника с понятным сообщением.
    std::fs::create_dir_all(&out_dir).expect("не создать папку");

    // --- Аудио-устройство (cpal) ---
    // Хост — аудио-подсистема ОС (на твоём Mac это CoreAudio).
    let host = cpal::default_host();
    // Устройство ввода по умолчанию — твоя гарнитура.
    let device = host.default_input_device().expect("входное устройство не найдено");
    // Дефолтная конфигурация входа: частота, число каналов, размер буфера, формат.
    let config = device.default_input_config().expect("нет дефолтной конфигурации входа");
    // В cpal 0.18 SampleRate — это просто алиас типа u32 (в старых версиях была обёртка .0).
    let sample_rate = config.sample_rate();    // например 48000 Гц — нативная частота гарнитуры
    let channels = config.channels() as usize; // обычно 1 или 2; `as` — каст между числовыми типами
    println!("Устройство: {device}"); // Device реализует трейт Display → печатается его имя
    println!("Частота: {sample_rate} Hz, каналов: {channels}");

    // --- Идемпотентность: не перезаписывать старые дубли ---
    // Если сессию прервать и запустить снова — продолжаем нумерацию с того же места.
    // ВАЖНО: берём МАКСИМАЛЬНЫЙ номер из имён файлов, а не количество файлов:
    // брак принято удалять вручную, от этого в нумерации появляются дырки,
    // и счётчик по количеству наехал бы на существующие файлы (перезапись!).
    //
    // read_dir возвращает Result<итератор по записям папки>.
    // .map(|d| ...) применяет замыкание к содержимому Ok.
    // filter_map(|e| e.ok()) — отбрасывает ошибки чтения отдельных файлов.
    // filter оставляет только файлы с расширением .wav (extension() даёт Option<&OsStr>).
    // map_or(false, ...) — если расширения нет, считаем false, иначе проверяем == "wav".
    // Из имени файла germes_real_0042.wav вытаскиваем число:
    // file_stem() → "germes_real_0042" (имя без расширения, Option),
    // to_str() → &str (Option: имена файлов бывают не-UTF8),
    // rsplit('_').next() → последний кусок после '_', т.е. "0042",
    // parse::<usize>() → число. Любой сбой на цепочке — None, и файл просто
    // не участвует в поиске максимума (filter_map такие пропускает).
    // Если read_dir совсем упал (например, папки нет) — unwrap_or(0) даёт ноль.
    let existing = std::fs::read_dir(&out_dir)
        .map(|d| d.filter_map(|e| e.ok())
            .filter(|e| e.path().extension().map_or(false, |x| x == "wav"))
            .filter_map(|e| {
                // let нужен, чтобы PathBuf пережил всю цепочку заимствований:
                // file_stem() возвращает ссылку НА PathBuf, а не на диск.
                let p = e.path();
                let stem = p.file_stem()?.to_str()?; // "germes_real_0042"
                stem.rsplit('_').next()?             // "0042"
                    .parse::<usize>()
                    .ok()
            })
            .max()
            .unwrap_or(0))
        .unwrap_or(0);

    // Сколько сэмплов в одном дубле = sample_rate * 1.2 секунды.
    // Пишем * 12 / 10 вместо * 1.2, чтобы остаться в целых числах (usize не бывает дробным).
    let take_samples = sample_rate as usize * 12 / 10;

    // --- Цикл по дублям: existing..(existing + count) — диапазон Range ---
    for i in existing..(existing + count) {
        println!("\n[{}/{}] Приготовься... скажи «Гермес»!", i + 1, existing + count);
        // Одна секунда на вдох и подготовку. sleep приостанавливает текущий поток.
        std::thread::sleep(std::time::Duration::from_secs(1));

        // --- Буфер сэмплов: центральный момент программы ---
        // Аудио приходит из ОТДЕЛЬНОГО потока (его вызывает аудио-драйвер), а читать
        // буфер мы будем из main. Данные, общие для двух потоков, в Rust требуют:
        //   Arc  — атомарный счётчик ссылок: clone() даёт вторую «ссылку-владельца»,
        //          данные живут, пока жива хотя бы одна ссылка;
        //   Mutex — взаимный замок: lock() даёт эксклюзивный доступ, второй поток ждёт.
        // Вместе: Arc<Mutex<Vec<f32>>> — общий вектор сэмплов с безопасным доступом.
        let buf: Arc<Mutex<Vec<f32>>> = Arc::new(Mutex::new(Vec::new()));
        let buf_in = buf.clone(); // вторая ссылка — её заберёт колбэк (clone у Arc дешёвый)
        let ch = channels;        // копия числа для move-замыкания ниже

        // Открываем входной поток. Аргументы:
        //   1. StreamConfig (частота/каналы/буфер) — получается из SupportedStreamConfig методом .config();
        //   2. колбэк данных — вызывается драйвером на каждой порции сэмплов;
        //   3. колбэк ошибок — если устройство отвалилось на лету;
        //   4. таймаут открытия: None = ждать сколько нужно.
        let stream = device.build_input_stream(
            config.config(),
            // `move` перед замыканием: оно ЗАБИРАЕТ buf_in и ch в себя (переход владения),
            // потому что колбэк будет жить в другом потоке дольше, чем текущий оборот цикла.
            // data: &[f32] — срез сэмплов от -1.0 до 1.0; второй аргумент (тайминги) не нужен — _.
            move |data: &[f32], _| {
                // Захватываем мьютекс. unwrap: паника возможна только если мьютекс «отравлен»
                // (в прошлом потоке паника под замком) — у нас такое невозможно.
                let mut b = buf_in.lock().unwrap();
                // data — ПЛОСКИЙ массив: при 2 каналах это [L,R,L,R,...].
                // chunks(ch) режет его на кадры по ch сэмплов — один кадр = один момент времени.
                for frame in data.chunks(ch) {
                    if b.len() >= take_samples { break; } // окно 1.2с заполнено — стоп
                    // Сводим в моно на лету: среднее по каналам кадра.
                    // sum::<f32>() — турборыба: явно говорим, каким типом суммировать.
                    b.push(frame.iter().sum::<f32>() / ch as f32);
                }
            },
            |err| eprintln!("ошибка потока: {err}"),
            None,
        ).expect("не удалось открыть аудиопоток (проверь доступ к микрофону!)");
        // ↑ На macOS здесь падает, если терминалу не дали доступ к микрофону
        //   (Системные настройки → Конфиденциальность → Микрофон).

        stream.play().expect("play failed"); // старт: драйвер начинает звать колбэк

        // main-поток ждёт, пока колбэк наберёт полное окно. Простейший способ —
        // опрос каждые 50 мс (можно было бы использовать канал или condvar, но тут избыточно).
        loop {
            std::thread::sleep(std::time::Duration::from_millis(50));
            if buf.lock().unwrap().len() >= take_samples { break; }
        }
        // Явно разрушаем поток: в cpal Drop у Stream останавливает и закрывает запись.
        // Без этого поток жил бы до конца итерации и мог захватить лишние сэмплы.
        drop(stream);

        // Достаём готовый дубль. clone() возвращает независимую Vec<f32>,
        // а замок мьютекса (временный MutexGuard) тут же освобождается.
        let samples = buf.lock().unwrap().clone();
        // {:04} — число минимум в 4 цифры, дополненное нулями: 7 → "0007".
        let path = format!("{out_dir}/germes_real_{:04}.wav", i + 1);
        write_wav(&path, &samples, sample_rate);
        println!("Сохранено: {path}");

        // Пауза между дублями — перевести дух перед следующим «Приготовься...».
        std::thread::sleep(std::time::Duration::from_millis(800));
    }
    println!("\nГотово. Файлы в {out_dir}");
}

// --- Запись WAV-файла (hound) ---
// path — куда писать; samples — сэмплы f32 в диапазоне [-1.0, 1.0]; rate — частота в Гц.
fn write_wav(path: &str, samples: &[f32], rate: u32) {
    // WAV-заголовок описывается структурой WavSpec.
    let spec = hound::WavSpec {
        channels: 1,                             // моно
        sample_rate: rate,                       // нативная частота микрофона (например 48000)
        bits_per_sample: 16,                     // 16 бит — стандарт для аудио-датасетов
        sample_format: hound::SampleFormat::Int, // целочисленный PCM, не float
    };
    let mut w = hound::WavWriter::create(path, spec).unwrap();
    for s in samples {
        // Перевод f32 → i16: умножаем на 32767 (максимальное положительное i16).
        // clamp(-1.0, 1.0) страхует от переполнения i16 на пиках громкости.
        w.write_sample((s.clamp(-1.0, 1.0) * 32767.0) as i16).unwrap();
    }
    w.finalize().unwrap(); // дописывает размеры в заголовок WAV; без него файл будет битый
}
